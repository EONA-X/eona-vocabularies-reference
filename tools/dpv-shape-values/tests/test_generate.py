import contextlib
import io
import re
import shutil
import tempfile
import unittest
from pathlib import Path

from rdflib import Graph, URIRef

import generate

HERE = Path(__file__).resolve().parent
FIX = HERE / "fixtures"
DPV = "https://w3id.org/dpv#"
PD = "https://w3id.org/dpv/pd#"
REPO = HERE.parents[2]


def load(*names):
    g = Graph()
    for n in names:
        g.parse(FIX / n, format="turtle")
    return g


def local_names(iris):
    return [i.split("#")[1] for i in iris]


def run(argv):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = generate.main(argv)
    return code, out.getvalue() + err.getvalue()


class Descendants(unittest.TestCase):
    def test_descendants_transitive_and_root_excluded(self):
        got = generate.descendants(load("mini-dpv.ttl"), URIRef(DPV + "Purpose"), [DPV])
        names = local_names(got)
        self.assertIn("B", names)
        self.assertIn("A", names)
        self.assertNotIn("Purpose", names)

    def test_descendants_follows_subclassof_too(self):
        got = generate.descendants(load("mini-dpv.ttl"), URIRef(DPV + "Purpose"), [DPV])
        self.assertIn("C", local_names(got))

    def test_namespace_filter(self):
        got = generate.descendants(load("mini-dpv.ttl"), URIRef(DPV + "Purpose"), [DPV])
        self.assertNotIn("Z", local_names(got))
        self.assertTrue(all(i.startswith(DPV) for i in got))
        self.assertNotIn("Foo", local_names(got))

    def test_sorted_deterministic(self):
        got = generate.descendants(load("mini-dpv.ttl"), URIRef(DPV + "Purpose"), [DPV])
        self.assertEqual(local_names(got), ["A", "B", "C"])

    def test_personal_data_spans_both_namespaces(self):
        sets = generate.value_sets(load("mini-dpv.ttl", "mini-pd.ttl"))
        self.assertEqual(sets["personal_data"],
                         [PD + "EmailAddress", PD + "EmailAddressWork", DPV + "PdTop"])
        self.assertNotIn(PD + "Other", sets["personal_data"])

    def test_consent_split(self):
        sets = generate.value_sets(load("mini-dpv.ttl", "mini-pd.ttl"))
        self.assertEqual(sets["consent_valid"], [DPV + "ConsentGiven"])
        self.assertEqual(sets["consent_invalid"],
                         [DPV + "ConsentRefused", DPV + "ConsentWithdrawn"])


class Render(unittest.TestCase):
    def test_empty_value_set_exits_2_with_message(self):
        with tempfile.TemporaryDirectory() as d:
            root = Path(d)
            (root / "dpv" / "v2.3").mkdir(parents=True)
            (root / "dpv-pd" / "v2.3").mkdir(parents=True)
            # mini-dpv has no consent subtree under this root once Purpose is all that is kept
            (root / "dpv" / "v2.3" / "ontology.ttl").write_text(
                "@prefix dpv: <https://w3id.org/dpv#> .\n"
                "@prefix skos: <http://www.w3.org/2004/02/skos/core#> .\n"
                "dpv:Purpose a skos:Concept .\n")
            (root / "dpv-pd" / "v2.3" / "ontology.ttl").write_text("")
            shapes = root / "shapes.ttl"
            shapes.write_text(
                "# BEGIN GENERATED by tools/dpv-shape-values: do not edit\n# END GENERATED\n")
            code, out = run(["--check", "--root", str(root), "--shapes", str(shapes)])
        self.assertEqual(code, 2)
        self.assertIn("empty", out)
        self.assertNotIn("Traceback", out)

    def test_pattern_anchored_and_escaped(self):
        sets = generate.value_sets(load("mini-dpv.ttl", "mini-pd.ttl"))
        block = generate.render_block(sets)
        # Turtle string "\\." is the regex \.
        patterns = [m.replace("\\\\", "\\") for m in re.findall(r'sh:pattern "([^"\n]*)"', block)]
        self.assertEqual(len(patterns), 4)
        purpose = re.compile(patterns[0])
        self.assertTrue(purpose.search(DPV + "A"))
        self.assertFalse(purpose.search("http://w3id.org/dpv#A"))
        self.assertFalse(purpose.search("dpv:A"))
        self.assertFalse(purpose.search(DPV + "AB"))
        self.assertFalse(purpose.search("xhttps://w3id.org/dpv#A"))
        self.assertFalse(purpose.search("https://w3idxorg/dpv#A"))
        pd = re.compile(patterns[1])
        self.assertTrue(pd.search(PD + "EmailAddress"))
        self.assertTrue(pd.search(DPV + "PdTop"))
        self.assertFalse(pd.search(PD + "PdTop"))
        self.assertFalse(pd.search(DPV + "EmailAddress"))

    def test_block_parses_as_turtle(self):
        sets = generate.value_sets(load("mini-dpv.ttl", "mini-pd.ttl"))
        text = ("@prefix eoxs: <https://eona-x.eu/shape/odrl-profile-shapes/v0.0.9#> .\n"
                "@prefix sh: <http://www.w3.org/ns/shacl#> .\n"
                "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .\n"
                "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n"
                + generate.render_block(sets))
        g = Graph()
        g.parse(data=text, format="turtle")
        self.assertGreater(len(g), 0)


class Cli(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        self.addCleanup(shutil.rmtree, self.tmp)
        (self.tmp / "dpv/v2.3").mkdir(parents=True)
        (self.tmp / "dpv-pd/v2.3").mkdir(parents=True)
        shutil.copy(FIX / "mini-dpv.ttl", self.tmp / "dpv/v2.3/ontology.ttl")
        shutil.copy(FIX / "mini-pd.ttl", self.tmp / "dpv-pd/v2.3/ontology.ttl")
        d = self.tmp / "eonax-odrl-profile-shapes/v0.0.9"
        d.mkdir(parents=True)
        self.shapes = d / "ontology.ttl"

    def test_check_reports_drift(self):
        shutil.copy(FIX / "shapes-stale.ttl", self.shapes)
        code, out = run(["--check", "--root", str(self.tmp)])
        self.assertEqual(code, 1)
        self.assertIn("Old", out)

    def test_write_then_check_clean(self):
        shutil.copy(FIX / "shapes-stale.ttl", self.shapes)
        self.assertEqual(run(["--write", "--root", str(self.tmp)])[0], 0)
        self.assertEqual(run(["--check", "--root", str(self.tmp)])[0], 0)
        text = self.shapes.read_text()
        self.assertIn("EmailAddressWork", text)
        self.assertNotIn("Old", text)

    def test_missing_markers_exit_2(self):
        self.shapes.write_text("@prefix sh: <http://www.w3.org/ns/shacl#> .\n")
        self.assertEqual(run(["--check", "--root", str(self.tmp)])[0], 2)
        self.assertEqual(run(["--write", "--root", str(self.tmp)])[0], 2)

    def test_duplicate_markers_exit_2(self):
        stale = (FIX / "shapes-stale.ttl").read_text()
        self.shapes.write_text(stale + stale)
        self.assertEqual(run(["--check", "--root", str(self.tmp)])[0], 2)

    def test_newest_shapes_version_is_the_target(self):
        d = self.tmp / "eonax-odrl-profile-shapes/v0.0.10"
        d.mkdir()
        shutil.copy(FIX / "shapes-stale.ttl", self.shapes)
        shutil.copy(FIX / "shapes-stale.ttl", d / "ontology.ttl")
        self.assertEqual(run(["--write", "--root", str(self.tmp)])[0], 0)
        self.assertIn("EmailAddressWork", (d / "ontology.ttl").read_text())
        self.assertIn("Old", self.shapes.read_text())


