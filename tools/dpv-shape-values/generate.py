#!/usr/bin/env python3
"""Generate the DPV 2.3 value lists of the Eona-X ODRL profile shapes.

Reads dpv/v2.3/ontology.ttl and dpv-pd/v2.3/ontology.ttl and writes, between the
markers BEGIN GENERATED / END GENERATED of the newest
eonax-odrl-profile-shapes/v*/ontology.ttl, one helper sh:NodeShape per value set:
the DPV purposes, the DPV personal-data categories (dpv: and pd:), and the DPV
consent statuses valid and invalid for processing.

  python -I tools/dpv-shape-values/generate.py --check   # exit 1 on drift
  python -I tools/dpv-shape-values/generate.py --write   # rewrite the block

Exit codes: 0 clean or written, 1 drift (--check), 2 markers missing or duplicated, or a value set is empty.
"""
import argparse
import difflib
import re
import sys
from pathlib import Path

from rdflib import Graph, URIRef
from rdflib.namespace import RDFS, SKOS

DPV = "https://w3id.org/dpv#"
PD = "https://w3id.org/dpv/pd#"
BEGIN = "# BEGIN GENERATED by tools/dpv-shape-values: do not edit"
END = "# END GENERATED"

SHAPES = (
    # (set key, shape local name, label)
    ("purpose", "DpvPurposeValue", "DPV 2.3 purpose (descendant of dpv:Purpose)"),
    ("personal_data", "DpvPersonalDataValue",
     "DPV 2.3 personal-data category (descendant of dpv:PersonalData, in dpv: or pd:)"),
    ("consent_valid", "DpvConsentValidValue",
     "DPV 2.3 consent status valid for processing"),
    ("consent_invalid", "DpvConsentInvalidValue",
     "DPV 2.3 consent status invalid for processing"),
)


def descendants(graph, root, namespaces):
    """Transitive closure over inverse skos:broader and inverse rdfs:subClassOf.

    The root is excluded; only IRIs starting with one of `namespaces` are kept,
    sorted by local name.
    """
    seen = set()
    todo = [root]
    while todo:
        node = todo.pop()
        for pred in (SKOS.broader, RDFS.subClassOf):
            for child in graph.subjects(pred, node):
                if isinstance(child, URIRef) and child not in seen and child != root:
                    seen.add(child)
                    todo.append(child)
    keep = [str(i) for i in seen if any(str(i).startswith(ns) for ns in namespaces)]
    return sorted(keep, key=lambda i: (i.split("#", 1)[1], i))


def value_sets(graph):
    d = lambda name: URIRef(DPV + name)  # noqa: E731
    return {
        "purpose": descendants(graph, d("Purpose"), [DPV]),
        "personal_data": descendants(graph, d("PersonalData"), [DPV, PD]),
        "consent_valid": descendants(graph, d("ConsentStatusValidForProcessing"), [DPV]),
        "consent_invalid": descendants(graph, d("ConsentStatusInvalidForProcessing"), [DPV]),
    }


def _esc(text):
    """Regex-escape the characters of an IRI that are special in an XPath regex."""
    return re.sub(r"([.^$*+?{}\[\]\\|()])", r"\\\1", text)


def _pattern(iris):
    by_ns = {}
    for iri in iris:
        ns, local = iri.split("#", 1)
        by_ns.setdefault(ns + "#", []).append(local)
    alts = []
    for ns in sorted(by_ns):
        names = "|".join(_esc(n) for n in sorted(by_ns[ns]))
        alts.append(f"{_esc(ns)}({names})")
    body = alts[0] if len(alts) == 1 else "(" + "|".join(alts) + ")"
    regex = f"^{body}$"
    return regex.replace("\\", "\\\\")  # Turtle string escape


def render_block(sets):
    out = [BEGIN]
    for key, name, label in SHAPES:
        out.append(f"""
eoxs:{name}
    a sh:NodeShape ;
    rdfs:label "{label}"@en ;
    sh:nodeKind sh:Literal ;
    sh:or ( [ sh:datatype xsd:string ] [ sh:datatype xsd:anyURI ] ) ;
    sh:pattern "{_pattern(sets[key])}" .""")
    out.append(END)
    return "\n".join(out)


def newest_shapes(root):
    def key(p):
        return [int(x) for x in re.findall(r"\d+", p.parent.name)]
    found = sorted(root.glob("eonax-odrl-profile-shapes/v*/ontology.ttl"), key=key)
    return found[-1] if found else None


def replace_block(text, block):
    if text.count(BEGIN) != 1 or text.count(END) != 1 or text.index(BEGIN) > text.index(END):
        return None
    start = text.index(BEGIN)
    end = text.index(END) + len(END)
    return text[:start] + block + text[end:]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=".")
    ap.add_argument("--shapes", help="shapes ontology.ttl to update (default: newest)")
    args = ap.parse_args(argv)
    root = Path(args.root)

    g = Graph()
    for rel in ("dpv/v2.3/ontology.ttl", "dpv-pd/v2.3/ontology.ttl"):
        g.parse(root / rel, format="turtle")
    sets = value_sets(g)
    empty = sorted(k for k, v in sets.items() if not v)
    if empty:
        print("empty DPV value set(s): " + ", ".join(empty)
              + "; an upstream class was probably renamed or moved", file=sys.stderr)
        return 2
    block = render_block(sets)

    target = Path(args.shapes) if args.shapes else newest_shapes(root)
    if target is None or not target.exists():
        print("no eonax-odrl-profile-shapes/v*/ontology.ttl found", file=sys.stderr)
        return 2
    old = target.read_text()
    new = replace_block(old, block)
    if new is None:
        print(f"{target}: exactly one BEGIN GENERATED and one END GENERATED marker "
              "are required, in that order", file=sys.stderr)
        return 2
    if args.write:
        target.write_text(new)
        return 0
    if new != old:
        sys.stdout.writelines(difflib.unified_diff(
            old.splitlines(keepends=True), new.splitlines(keepends=True),
            fromfile=f"{target} (committed)", tofile=f"{target} (generated)"))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
