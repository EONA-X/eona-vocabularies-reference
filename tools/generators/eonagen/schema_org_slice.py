"""Slice of the schema.org release: Reservation, Trip, ProgramMembership.

python -I -m eonagen.schema_org_slice --source FILE --out FILE
The source is read as data (rdflib parse), never executed.
"""
import argparse
import hashlib
import sys

from rdflib import BNode, Graph, Literal, URIRef
from rdflib.namespace import OWL, RDF, RDFS, XSD

from eonagen.turtle import Anon, write_turtle

S = "https://schema.org/"
SCHEMA = lambda n: URIRef(S + n)  # noqa: E731
DCTERMS = "http://purl.org/dc/terms/"
VERSION = "30.1"
COMMIT = "5f2d8cdec99b7329459ef6584e94b6a840f88471"
RELEASE_FILE = "data/releases/30.1/schemaorg-current-https.ttl"
SEEDS = ("Reservation", "Trip", "ProgramMembership")

PREFIXES = {"rdf": str(RDF), "rdfs": str(RDFS), "owl": str(OWL), "xsd": str(XSD),
            "schema": S, "dcterms": DCTERMS}


class MissingSeed(Exception):
    pass


def _subclosure(g, root):
    seen, todo = {root}, [root]
    while todo:
        c = todo.pop()
        for sub in g.subjects(RDFS.subClassOf, c):
            if sub not in seen:
                seen.add(sub)
                todo.append(sub)
    return seen


def _superclosure(g, classes):
    seen, todo = set(), list(classes)
    while todo:
        c = todo.pop()
        for sup in g.objects(c, RDFS.subClassOf):
            if isinstance(sup, URIRef) and sup not in seen:
                seen.add(sup)
                todo.append(sup)
    return seen


def seed_classes(g):
    for name in SEEDS:
        if (SCHEMA(name), None, None) not in g:
            raise MissingSeed("upstream file has no schema:" + name)
    return (_subclosure(g, SCHEMA("Reservation")) | _subclosure(g, SCHEMA("Trip"))
            | {SCHEMA("ProgramMembership")})


def slice_properties(g, seeds):
    return {p for c in seeds for p in g.subjects(SCHEMA("domainIncludes"), c)}


def _term(g, o):
    if isinstance(o, BNode):
        return Anon((p, _term(g, x)) for p, x in g.predicate_objects(o))
    return o


def _emit(g, subject, predicates=None):
    return [(subject, p, _term(g, o)) for p, o in g.predicate_objects(subject)
            if predicates is None or p in predicates]


def slice_triples(g):
    seeds = seed_classes(g)
    props = slice_properties(g, seeds)
    triples = []
    for s in sorted(seeds | props, key=str):
        triples += _emit(g, s)

    # classes referenced from the slice but outside it: reduced description
    refs = set()
    for p in props:
        for pred in ("domainIncludes", "rangeIncludes"):
            refs |= {o for o in g.objects(p, SCHEMA(pred)) if isinstance(o, URIRef)}
    refs -= seeds
    stubs = (refs | _superclosure(g, seeds | refs)) - seeds
    for c in sorted(stubs, key=str):
        triples += _emit(g, c, {RDF.type, RDFS.label, RDFS.subClassOf})

    # members of enumerations used as a range
    members = set()
    for c in stubs:
        members |= {m for m in g.subjects(RDF.type, c) if isinstance(m, URIRef)}
    for m in sorted(members - seeds - props - stubs, key=str):
        triples += _emit(g, m, {RDF.type, RDFS.label, RDFS.comment})
    return triples


def root_triples(source_sha256, commit, version):
    root = URIRef(S)
    src = "https://github.com/schemaorg/schemaorg/blob/%s/%s" % (commit, RELEASE_FILE)
    return [
        (root, RDF.type, OWL.Ontology),
        (root, OWL.versionInfo, Literal(version)),
        (root, RDFS.label, Literal("schema.org travel subset", lang="en")),
        (root, URIRef(DCTERMS + "source"), URIRef(src)),
        (root, URIRef(DCTERMS + "license"), URIRef("https://creativecommons.org/licenses/by-sa/3.0/")),
    ]


def slice_to_turtle(g, source_sha256, commit=COMMIT, version=VERSION):
    triples = slice_triples(g) + root_triples(source_sha256, commit, version)
    header = [
        "Generated by tools/generators (eonagen.schema_org_slice). Do not edit by hand.",
        "Source: https://github.com/schemaorg/schemaorg/blob/%s/%s" % (commit, RELEASE_FILE),
        "Source sha256: " + source_sha256,
        "Licence of the source data: CC BY-SA 3.0 (https://schema.org/docs/terms.html)",
        "Regenerate: tools/generators/regenerate.sh schema-org-travel",
    ]
    return write_turtle(triples, PREFIXES, header=header, root=URIRef(S))


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    with open(a.source, "rb") as f:
        data = f.read()
    g = Graph().parse(data=data, format="turtle")
    text = slice_to_turtle(g, hashlib.sha256(data).hexdigest())
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
